import { test, expect } from '@playwright/test'

test('real HTTP advance lifecycle, partial and none decisions, browser full deduction and posting exactly once', async ({ playwright, request }) => {
  test.setTimeout(120000)
  const api = process.env.FINANCE_API_URL || 'http://127.0.0.1:8001/api'
  const login = await request.post(`${api}/auth/login`, { headers: { Accept: 'application/json' }, data: { email: 'finance-e2e@example.test', password: 'FinanceE2E123!' } })
  expect(login.status()).toBe(200)
  const auth = await login.json()
  const headers = { Accept: 'application/json', Authorization: `Bearer ${auth.token}` }
  const post = async (path, data, status = 200) => {
    const response = await request.post(api + path, { headers, data }); expect(response.status(), await response.text()).toBe(status); return response.json()
  }
  const get = async path => { const response = await request.get(api + path, { headers }); expect(response.status()).toBe(200); return response.json() }
  const employee = await post('/employees', { employee_number: `FIN-E2E-${Date.now()}`, full_name: 'موظف اختبار سلف متكامل', company: 'شركة الاختبار المعزولة', hire_date: '2020-01-01', status: 'active', basic_salary: 6000 }, 201)
  const advance = await post('/advances', { employee_id: employee.id, reference_number: `ADV-E2E-${Date.now()}`, original_amount: 5000 }, 201)
  await post(`/advances/${advance.id}/approve`, { approval_reference: `APP-${advance.id}` })
  const date = new Date().toLocaleDateString('en-CA', { timeZone: 'Asia/Riyadh' })
  await post(`/advances/${advance.id}/movements`, { type: 'disbursement', transaction_date: date, reference_number: `BANK-${advance.id}`, idempotency_key: `BANK-${advance.id}`, method: 'bank' }, 201)
  await post(`/advances/${advance.id}/movements`, { type: 'external_repayment', amount: 1500, transaction_date: date, reference_number: `REPAY-${advance.id}`, idempotency_key: `REPAY-${advance.id}`, method: 'bank' }, 201)
  expect((await get(`/advances/${advance.id}`)).balance).toBe('3500')
  const base = { employee_id: employee.id, transaction_type: 'final_settlement', transaction_date: date, last_working_date: '2026-01-01', termination_type: 'termination', actual_notice_days: 60, unpaid_days: 0, remaining_leave_days: 0 }
  for (const decision of [{ choice: 'partial', allocations: [{ advance_id: advance.id, amount: 1000 }], reason: 'خصم جزئي موثق', remaining_debt_reason: 'المديونية المتبقية قائمة' }, { choice: 'none', reason: 'تحصيل السلفة بشكل مستقل', remaining_debt_reason: 'يبقى الدين قائمًا' }]) {
    const settlement = await post('/hr-transactions', { ...base, advance_decision: decision }, 201)
    expect(Number(settlement.total_deductions)).toBe(decision.choice === 'partial' ? 1000 : 0)
    expect(Number(settlement.net_amount)).toBe(21000 - Number(settlement.total_deductions))
    await post(`/hr-transactions/${settlement.id}/financial-cancel`, { reason: 'انتهاء تجربة القرار دون ترحيل' })
    expect((await get(`/advances/${advance.id}`)).balance).toBe('3500')
  }
  const browser = await playwright.chromium.launch({ executablePath: process.env.CHROME_PATH || 'C:/Program Files/Google/Chrome/Application/chrome.exe', args: ['--disable-gpu', '--renderer-process-limit=1'], timeout: 15000 })
  try {
  const context = await browser.newContext({ baseURL: process.env.E2E_BASE_URL || 'http://127.0.0.1:5173' })
  const page = await context.newPage()
  await page.addInitScript(({ token, user }) => { localStorage.setItem('auth_token', token); localStorage.setItem('user', JSON.stringify(user)) }, auth)
  await page.route('**/api/**', async route => { const url = new URL(route.request().url()); const response = await route.fetch({ url: api + url.pathname.replace(/^\/api/, '') + url.search }); await route.fulfill({ response }) })
  page.on('dialog', dialog => dialog.accept())
  page.on('pageerror', error => { throw error })
  await page.goto(`/#/calculator?employee=${employee.id}`)
  await expect(page.getByText(/تنبيه مالي: يوجد على الموظف عدد 1 سلفة/)).toBeVisible({ timeout: 15000 })
  await page.getByRole('radio', { name: 'خصم كامل الرصيد المتاح بحد المستحقات' }).check()
  await page.getByRole('button', { name: 'احسب المخالصة', exact: true }).click()
  const saving = page.waitForResponse(response => new URL(response.url()).pathname === '/api/hr-transactions' && response.request().method() === 'POST')
  await page.getByRole('button', { name: 'حفظ المعاملة', exact: true }).click()
  const savedResponse = await saving; expect(savedResponse.status()).toBe(201); const saved = await savedResponse.json()
  expect(Number(saved.total_deductions)).toBe(3500)
  expect((await get(`/advances/${advance.id}`)).balance).toBe('3500')
  await page.goto(`/#/transactions/${saved.id}`)
  await page.getByRole('button', { name: 'إرسال للمراجعة', exact: true }).click()
  await page.getByLabel('مصدر خصم السلف').selectOption('non_wage')
  await page.getByLabel('الحد القابل للحسم بعد المراجعة').fill('3500')
  for (const label of ['تحققت من صحة المديونية وطبيعتها', 'راجعت المستندات والموافقات', 'راجعت الحدود والحقوق المحمية ومصدر الخصم']) await page.getByRole('checkbox', { name: label }).check()
  await page.getByLabel('تفسير المراجعة المالية').fill('مطابقة مستندات السلفة وإثبات السداد وتحديد مصدر الخصم')
  const reviewing = page.waitForResponse(response => response.url().endsWith('/financial-review'))
  await page.getByRole('button', { name: 'تسجيل المراجعة المالية', exact: true }).click()
  expect((await reviewing).status()).toBe(200)
  const approving = page.waitForResponse(response => response.url().endsWith('/approve'))
  await page.getByRole('button', { name: 'اعتماد', exact: true }).click(); expect((await approving).status()).toBe(200)
  const posting = page.waitForResponse(response => response.url().endsWith('/post'))
  await page.getByRole('button', { name: 'ترحيل التسوية المالية وتخفيض السلف المخصصة' }).click()
  expect((await posting).status()).toBe(200)
  await expect(page.getByText('مرحلة ماليًا', { exact: true })).toBeVisible({ timeout: 15000 })
  await page.getByLabel('مرجع مستند الدفع').fill(`PAY-${saved.id}`)
  const paying = page.waitForResponse(response => response.url().endsWith('/pay'))
  await page.getByRole('button', { name: 'تسجيل مستند الصرف' }).click()
  expect((await paying).status()).toBe(200)
  await expect(page.getByText('مدفوعة', { exact: true })).toBeVisible({ timeout: 15000 })
  await page.close()
  const finance = await get(`/hr-transactions/${saved.id}/finance`)
  expect(finance.payments).toHaveLength(1)
  await post(`/hr-transactions/${saved.id}/post`, { idempotency_key: finance.settlement.posting_key })
  const finalAdvance = await get(`/advances/${advance.id}`)
  expect(finalAdvance.balance).toBe('0')
  expect(finalAdvance.transactions.filter(entry => entry.transaction_type === 'settlement')).toHaveLength(1)
  await post('/auth/logout', {})
  } finally { await browser.close() }
})
