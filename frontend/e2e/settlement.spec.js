test('admin adjustment preserves calculation, revert, real exports and print', async ({ page }) => {
  const errors = []
  page.on('pageerror', error => errors.push(error.message))
  await login(page, 'admin')
  await page.getByLabel('تاريخ المباشرة', { exact: true }).fill('2019-01-01')
  await page.getByLabel('تاريخ آخر يوم عمل', { exact: true }).fill('2026-01-01')
  await page.getByRole('combobox', { name: /^سبب انتهاء العلاقة/ }).selectOption('resignation')
  await wage(page)
  await calculate(page)
  const transaction = await save(page)
  await page.goto(`/#/transactions/${transaction.id}`)
  const row = page.getByRole('row').filter({ hasText: 'مكافأة نهاية الخدمة' })
  await row.getByRole('button', { name: 'تعديل', exact: true }).click()
  await page.getByLabel('القيمة الجديدة', { exact: true }).fill('17500')
  await page.getByLabel('سبب التعديل', { exact: true }).fill('Audit adjustment reason')
  const adjusted = page.waitForResponse(r => r.url().endsWith('/adjust'))
  await page.getByRole('button', { name: 'حفظ التعديل', exact: true }).click()
  expect((await adjusted).status()).toBe(200)
  await expect(page.getByRole('dialog')).toHaveCount(0)
  const details = await page.evaluate(async id => (await fetch(`/api/hr-transactions/${id}`, { headers: { Accept: 'application/json', Authorization: `Bearer ${localStorage.getItem('auth_token')}` } })).json(), transaction.id)
  const eos = details.financial_items.find(i => i.code === 'end_of_service')
  expect(eos.calculated_amount).toBe('18000.00')
  expect(eos.approved_amount).toBe('17500.00')
  expect(eos.difference_amount).toBe('-500.00')
  await row.getByRole('button', { name: 'تعديل', exact: true }).click()
  const reverted = page.waitForResponse(r => r.url().endsWith('/revert-adjustment'))
  await page.getByRole('button', { name: 'إعادة للقيمة المحسوبة', exact: true }).click()
  expect((await reverted).status()).toBe(200)
  await expect(page.getByRole('dialog')).toHaveCount(0)
  for (const kind of ['Excel', 'PDF']) {
    const pending = page.waitForEvent('download')
    await page.getByRole('button', { name: kind, exact: true }).click()
    const file = await pending
    expect(await file.failure()).toBeNull()
    expect(file.suggestedFilename()).toMatch(kind === 'Excel' ? /\.xlsx$/ : /\.pdf$/)
    const bytes = await readFile(await file.path())
    expect(bytes.subarray(0, kind === 'Excel' ? 2 : 4).toString()).toBe(kind === 'Excel' ? 'PK' : '%PDF')
  }
  await page.getByRole('button', { name: 'طباعة', exact: true }).click()
  await expect(page.getByText(transaction.reference_number, { exact: true }).first()).toBeVisible()
  await page.emulateMedia({ media: 'print' })
  await expect(page.locator('body')).not.toContainText('T00:00:00')
  await page.screenshot({ path: 'test-results/print-preview.png', fullPage: true })
  expect(errors).toEqual([])
})
