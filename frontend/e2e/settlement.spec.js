import { test, expect } from '@playwright/test'
import { readFile } from 'node:fs/promises'

async function chooseEmployee(page, id) {
  await page.getByRole('combobox', { name: 'البحث عن الموظف' }).click()
  await page.locator('[role="option"][data-employee-id="' + id + '"]').click()
  await expect(page.getByRole('button',{name:'إلغاء اختيار الموظف',exact:true})).toBeVisible()
}

async function login(page, role = 'hr') {
  await page.goto('/')
  await page.getByLabel('البريد الإلكتروني').fill(`${role}@audit.test`)
  await page.getByLabel('كلمة المرور').fill('audit-test-password')
  const pending = page.waitForResponse(r => r.url().endsWith('/auth/login'))
  await page.getByRole('button', { name: 'دخول', exact: true }).click()
  expect((await pending).status()).toBe(200)
  if (role === 'reviewer') return
  await chooseEmployee(page, 1)
  await page.getByRole('combobox', { name: 'العقد', exact: true }).selectOption('1')
  await page.getByLabel('تاريخ آخر مباشرة بعد الإجازة السابقة (اختياري)', { exact: true }).fill('2025-01-01')
}

async function calculate(page) {
  const salaryDays=page.getByLabel('أيام الراتب غير المدفوع',{exact:true})
  if (await salaryDays.count()) await salaryDays.fill('0')
  else await page.getByLabel('أيام الراتب المستحقة',{exact:true}).fill('0')
  const pending = page.waitForResponse(r => r.url().endsWith('/calculate'))
  await page.getByRole('button', { name: 'احسب المخالصة', exact: true }).click()
  const response = await pending
  expect(response.status()).toBe(200)
  return response.json()
}

async function save(page) {
  const pending = page.waitForResponse(r => r.url().endsWith('/hr-transactions') && r.request().method() === 'POST')
  await page.getByRole('button', { name: 'حفظ المعاملة', exact: true }).click()
  const response = await pending
  expect(response.status()).toBe(201)
  return response.json()
}

async function wage(page) {
  await page.getByLabel('الراتب الأساسي', { exact: true }).fill('6000')
  for (const label of ['بدل السكن', 'بدل النقل', 'بدلات أخرى']) await page.getByLabel(label, { exact: true }).fill('0')
}

