test('real final calculation, save, reload, HR submission and reviewer approval', async ({ page, browser }) => {
  const errors = []
  page.on('pageerror', error => errors.push(error.message))
  await login(page)
  await page.getByLabel('تاريخ المباشرة', { exact: true }).fill('2022-01-01')
  await page.getByLabel('تاريخ آخر يوم عمل', { exact: true }).fill('2026-01-01')
  await wage(page)
  const result = await calculate(page)
  expect(result.entitlements.find(i => i.code === 'end_of_service').amount).toBe('12000')
  await expect(page.getByRole('row').filter({ hasText: 'مكافأة نهاية الخدمة' })).toContainText('١٢٬٠٠٠٫٠٠')
  const transaction = await save(page)
  expect(Number(transaction.net_amount)).toBe(Number(result.net_settlement))
  await page.goto(`/#/transactions/${transaction.id}`)
  page.once('dialog', dialog => dialog.accept())
  await page.getByRole('button', { name: 'إرسال للمراجعة', exact: true }).click()
  await expect(page.getByText('بانتظار المراجعة', { exact: true }).first()).toBeVisible()
  const reviewer = await browser.newPage()
  await login(reviewer, 'reviewer')
  await reviewer.goto(`/#/transactions/${transaction.id}`)
  await reviewer.getByLabel('مصدر خصم السلف').selectOption('non_wage')
  await reviewer.getByLabel('الحد القابل للحسم بعد المراجعة').fill('0')
  for (const label of ['تحققت من صحة المديونية وطبيعتها','راجعت المستندات والموافقات','راجعت الحدود والحقوق المحمية ومصدر الخصم']) await reviewer.getByRole('checkbox',{name:label}).check()
  await reviewer.getByLabel('تفسير المراجعة المالية').fill('مراجعة مالية مكتملة لمعاملة الاختبار')
  const reviewing=reviewer.waitForResponse(response=>response.url().endsWith('/financial-review'))
  await reviewer.getByRole('button',{name:'تسجيل المراجعة المالية',exact:true}).click()
  expect((await reviewing).status()).toBe(200)
  await reviewer.getByRole('button', { name: 'اعتماد', exact: true }).click()
  await expect(reviewer.getByText('معتمدة', { exact: true }).first()).toBeVisible()
  await reviewer.close()
  expect(errors).toEqual([])
})

